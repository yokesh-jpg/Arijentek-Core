	# Resolve company: prioritize employee's company or proper default_company from Global Defaults
	company = doc.get("company")
	if not company and doc.get("employee"):
		company = frappe.db.get_value("Employee", doc.get("employee"), "company")
	if not company:
		company = frappe.db.get_single_value("Global Defaults", "default_company")
	if not company:
		company = frappe.defaults.get_user_default("Company") or frappe.defaults.get_user_default("company")
	if not company:
		company = frappe.db.get_value("Company", {}, "name")

	fields = [
		"employee",
		"salary_structure",
		"from_date",
		"base",
		"variable",
		"company",
		"payroll_payable_account"
	]

	for field in fields:
		if field in doc and doc.get(field) is not None:
			if field == "company" and not doc.get(field):
				continue
			ssa.set(field, doc.get(field))

	# Map frontend base_salary to DB base
	if "base_salary" in doc and doc.get("base_salary") is not None:
		ssa.set("base", doc.get("base_salary"))

	if company:
		ssa.company = company
	elif not ssa.company:
		ssa.company = frappe.db.get_single_value("Global Defaults", "default_company")

	# Check joining and relieving dates to raise custom formatted error messages before hrms validator
	if ssa.employee and ssa.from_date:
		employee_info = frappe.db.get_value("Employee", ssa.employee, ["date_of_joining", "relieving_date"], as_dict=True)
		if employee_info:
			joining_date = employee_info.get("date_of_joining")
			relieving_date = employee_info.get("relieving_date")

			if joining_date and frappe.utils.getdate(ssa.from_date) < frappe.utils.getdate(joining_date):
				frappe.throw(
					_("From Date {0} cannot be before employee's joining Date {1}").format(
						frappe.utils.format_date(ssa.from_date, "dd-mm-yyyy"),
						frappe.utils.format_date(joining_date, "dd-mm-yyyy")
					)
				)

			if relieving_date and frappe.utils.getdate(ssa.from_date) > frappe.utils.getdate(relieving_date):
				frappe.throw(
					_("From Date {0} cannot be after employee's relieving Date {1}").format(
						frappe.utils.format_date(ssa.from_date, "dd-mm-yyyy"),
						frappe.utils.format_date(relieving_date, "dd-mm-yyyy")
					)
				)

	# Check if from_date falls within an active Fiscal Year for this company
	if ssa.from_date and ssa.company:
		fiscal_year = frappe.db.sql(
			"""
			SELECT name FROM `tabFiscal Year`
			WHERE %s BETWEEN year_start_date AND year_end_date
			  AND disabled = 0
			  AND (
			      name NOT IN (SELECT parent FROM `tabFiscal Year Company`)
			      OR name IN (SELECT parent FROM `tabFiscal Year Company` WHERE company = %s)
			  )
			LIMIT 1
			""",
			(ssa.from_date, ssa.company),
			as_dict=True
		)
		if not fiscal_year:
			frappe.throw(
				_("Date {0} is not in any active Fiscal Year for {1}").format(
					frappe.utils.format_date(ssa.from_date, "dd-mm-yyyy"),
					ssa.company
				)
			)

	# Check if any active Salary Slip exists for this employee and structure
	if ssa.employee and ssa.salary_structure:
		existing_slip = frappe.db.exists(
			"Salary Slip",
			{
				"employee": ssa.employee,
				"salary_structure": ssa.salary_structure,
				"docstatus": ["!=", 2]
			}
		)
		if existing_slip:
			frappe.throw(_("Cannot save Salary Structure Assignment because Salary Slip {0} has already been created for this employee with this salary structure.").format(existing_slip))

	if ssa.docstatus == 1:
		ssa.db_set("docstatus", 0)

	ssa.save(ignore_permissions=False)
	ssa.submit()
	return ssa.name


