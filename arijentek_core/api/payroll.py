@frappe.whitelist()
def report_salary_slip_list(employee=None, month=None, year=None, status=None, slip_name=None, pdf=False):
	"""
	Returns detailed Salary Slip list for Payroll Report, supporting individual and summary PDF exports via simple_payslip.html.
	Enterprise-grade, optimized query execution avoiding redundant DB calls.
	"""
	if not can_view_all_payroll():
		frappe.throw(_("You are not authorized to view payroll reports"), frappe.PermissionError)
	from frappe.utils import cint, flt, now_datetime
	from frappe.utils.pdf import get_pdf

	# If specific single slip PDF requested, delegate to download_payslip_pdf in payslip_generator
	is_pdf = cint(pdf) if isinstance(pdf, (int, str)) and str(pdf).isdigit() else frappe.parse_json(pdf)
	if is_pdf and slip_name:
		from arijentek_core.payroll.payslip_generator import download_payslip_pdf
		return download_payslip_pdf(slip_name)

	columns = [
		{"label": "Salary Slip ID", "fieldname": "name"},
		{"label": "Employee ID", "fieldname": "employee"},
		{"label": "Employee Name", "fieldname": "employee_name"},
		{"label": "Posting Date", "fieldname": "posting_date"},
		{"label": "Start Date", "fieldname": "start_date"},
		{"label": "End Date", "fieldname": "end_date"},
		{"label": "Gross Pay", "fieldname": "gross_pay"},
		{"label": "Total Deductions", "fieldname": "total_deduction"},
		{"label": "Net Pay", "fieldname": "net_pay"},
		{"label": "Status", "fieldname": "status"},
	]

	conditions = []
	params = {}

	if employee:
		conditions.append("ss.employee = %(employee)s")
		params["employee"] = employee

	if status and status.lower() != "all":
		if status.lower() == "submitted":
			conditions.append("ss.docstatus = 1")
		elif status.lower() == "draft":
			conditions.append("ss.docstatus = 0")
		elif status.lower() == "cancelled":
			conditions.append("ss.docstatus = 2")
		else:
			conditions.append("ss.status = %(status)s")
			params["status"] = status

	if year and str(year).isdigit():
		conditions.append("YEAR(ss.start_date) = %(year)s")
		params["year"] = cint(year)

	if month and str(month).isdigit():
		conditions.append("MONTH(ss.start_date) = %(month)s")
		params["month"] = cint(month)

	where_clause = f"WHERE {' AND '.join(conditions)}" if conditions else ""

	slips = frappe.db.sql(f"""
		SELECT
			ss.name,
			ss.employee,
			ss.employee_name,
			DATE_FORMAT(ss.posting_date, '%%Y-%%m-%%d') as posting_date,
			DATE_FORMAT(ss.start_date, '%%Y-%%m-%%d') as start_date,
			DATE_FORMAT(ss.end_date, '%%Y-%%m-%%d') as end_date,
			ROUND(COALESCE(ss.gross_pay, 0), 2) as gross_pay,
			ROUND(COALESCE(ss.total_deduction, 0), 2) as total_deduction,
			ROUND(COALESCE(ss.net_pay, 0), 2) as net_pay,
			CASE
				WHEN ss.docstatus = 1 THEN 'Submitted'
				WHEN ss.docstatus = 0 THEN 'Draft'
				WHEN ss.docstatus = 2 THEN 'Cancelled'
				ELSE ss.status
			END as status
		FROM `tabSalary Slip` ss
		{where_clause}
		ORDER BY ss.posting_date DESC, ss.name DESC
	""", params, as_dict=True)

	company_name = frappe.db.get_single_value("Global Defaults", "default_company") or "Company"
	company_currency = frappe.get_cached_value("Company", company_name, "default_currency") or "USD"
	currency_symbol = frappe.db.get_value("Currency", company_currency, "symbol") or "$"

	if is_pdf:
		total_gross = sum(flt(s.get("gross_pay")) for s in slips)
		total_ded = sum(flt(s.get("total_deduction")) for s in slips)
		total_net = sum(flt(s.get("net_pay")) for s in slips)

		context = {
			"report_title": _("Salary Slips & Payroll Summary Report"),
			"company_name": company_name,
			"currency_symbol": currency_symbol,
			"selected_employee": employee,
			"selected_month": month,
			"selected_year": year,
			"selected_status": status,
			"total_gross_pay": f"{total_gross:,.2f}",
			"total_deduction": f"{total_ded:,.2f}",
			"total_net_pay": f"{total_net:,.2f}",
			"generated_on": now_datetime().strftime("%Y-%m-%d %H:%M"),
			"columns": columns,
			"data": slips
		}

		html_content = frappe.render_template("arijentek_core/templates/reports/salary_slip_summary_report.html", context)

		pdf_options = {
			"page-size": "A4",
			"orientation": "Landscape",
			"margin-top": "10mm",
			"margin-bottom": "10mm",
			"margin-left": "8mm",
			"margin-right": "8mm",
			"encoding": "UTF-8"
		}

		pdf_binary = get_pdf(html_content, options=pdf_options)

		frappe.local.response.filename = f"Salary_Slips_Report_{now_datetime().strftime('%Y%m%d')}.pdf"
		frappe.local.response.filecontent = pdf_binary
		frappe.local.response.type = "pdf"
		return

	return {
		"columns": columns,
		"data": slips,
		"count": len(slips)
	}


