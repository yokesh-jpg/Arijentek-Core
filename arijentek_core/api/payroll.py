@frappe.whitelist()
def save_overtime_slip(doc):
	"""
	Saves or updates an Overtime Slip document.
	"""
	if isinstance(doc, str):
		import json
		doc = json.loads(doc)

	ot_name = doc.get("name")
	is_new = not ot_name or not frappe.db.exists("Overtime Slip", ot_name)

	if is_new:
		if not can_create_overtime_slip():
			frappe.throw(_("You do not have permission to create Overtime Slip"), frappe.PermissionError)
		ot_doc = frappe.new_doc("Overtime Slip")
	else:
		if not can_edit_overtime_slip():
			frappe.throw(_("You do not have permission to edit Overtime Slip"), frappe.PermissionError)
		ot_doc = frappe.get_doc("Overtime Slip", ot_name)

	ot_doc.employee = doc.get("employee")
	ot_doc.posting_date = doc.get("posting_date") or frappe.utils.nowdate()
	ot_doc.start_date = doc.get("start_date")
	ot_doc.end_date = doc.get("end_date")

	if doc.get("employee"):
		emp_info = frappe.db.get_value("Employee", doc.get("employee"), ["company", "department"], as_dict=True)
		if emp_info:
			ot_doc.company = emp_info.get("company") or frappe.defaults.get_user_default("company")
			ot_doc.department = emp_info.get("department")

	details_list = doc.get("overtime_details") or []
	ot_doc.set("overtime_details", [])
	total_duration = 0.0

	for detail in details_list:
		if isinstance(detail, dict) and detail.get("overtime_type"):
			dur = frappe.utils.flt(detail.get("overtime_duration", 0.0))
			total_duration += dur
			ot_doc.append("overtime_details", {
				"date": detail.get("date") or ot_doc.start_date,
				"overtime_type": detail.get("overtime_type"),
				"overtime_duration": dur,
				"standard_working_hours": frappe.utils.flt(detail.get("standard_working_hours", 8.0)),
			})

	ot_doc.total_overtime_duration = total_duration

	# Check salary structure assignment if any detail row uses Salary Component Based overtime type
	from hrms.payroll.doctype.salary_structure_assignment.salary_structure_assignment import (
		get_assigned_salary_structure,
	)

	for detail in details_list:
		if isinstance(detail, dict) and detail.get("overtime_type"):
			method = frappe.db.get_value("Overtime Type", detail.get("overtime_type"), "overtime_calculation_method")
			if method == "Salary Component Based":
				salary_structure = get_assigned_salary_structure(ot_doc.employee, ot_doc.start_date)
				if not salary_structure:
					frappe.throw(
						_("No active Salary Structure Assignment found for Employee {0} as of {1}. Please assign a Salary Structure first or select a Fixed Hourly Rate Overtime Type.").format(
							ot_doc.employee, ot_doc.start_date
						)
					)
					break

	if is_new:
		ot_doc.insert()
	else:
		ot_doc.save()

	frappe.db.set_value("Overtime Slip", ot_doc.name, "total_overtime_duration", total_duration)
	ot_doc.reload()

	if ot_doc.docstatus == 0:
		ot_doc.submit()

	res_dict = ot_doc.as_dict()
	res_dict["total_overtime_duration"] = total_duration
	res_dict["total_overtime_hours"] = total_duration
	ds = res_dict.get("docstatus", 0)
	res_dict["status"] = "Submitted" if ds == 1 else ("Cancelled" if ds == 2 else "Draft")
	return res_dict


