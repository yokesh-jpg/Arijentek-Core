@frappe.whitelist()
def get_employee_list():
	"""
	Get list of employees the current user is permitted to see.
	If they are System Manager, HR Manager, or have submit permission on Salary Slip, returns all active employees.
	Otherwise, returns only their own employee record.
	"""
	user = frappe.session.user
	roles = frappe.get_roles(user)

	if "System Manager" in roles or "HR Manager" in roles or frappe.has_permission("Salary Slip", "submit"):
		return frappe.get_all(
			"Employee",
			filters={"status": "Active"},
			fields=["name", "employee_name"],
			order_by="employee_name asc",
		)

	current_employee = _get_current_employee_id()
	if current_employee:
		emp_details = frappe.db.get_value(
			"Employee",
			{"name": current_employee, "status": "Active"},
			["name", "employee_name"],
			as_dict=True,
		)
		if emp_details:
			return [emp_details]
	return []


@frappe.whitelist()
def get_salary_slips(year: int | None = None, month: int | None = None, employee_id: str | None = None, limit: int = 50):
	"""
	Get salary slips using permissions.
	"""
	from frappe.utils import get_first_day, get_last_day

	filters = {"docstatus": 1}

	user = frappe.session.user
	roles = frappe.get_roles(user)
	has_global = "System Manager" in roles or "HR Manager" in roles or frappe.has_permission("Salary Slip", "submit")

	if not has_global:
		employee_id = _get_current_employee_id()
		if not employee_id:
			return []
		filters["employee"] = employee_id
	elif employee_id and employee_id != "all":
		filters["employee"] = employee_id

	if year:
		if month:
			start_date = get_first_day(f"{year}-{int(month):02d}-01")
			end_date = get_last_day(start_date)
			filters["start_date"] = ["between", [start_date, end_date]]
		else:
			filters["start_date"] = [">=", f"{year}-01-01"]
			filters["end_date"] = ["<=", f"{year}-12-31"]

	# Using get_list is the only way to match Core behavior 1:1 for Sam
	salary_slips = frappe.get_list(
		"Salary Slip",
		filters=filters,
		fields=[
			"name",
			"employee",
			"employee_name",
			"start_date",
			"end_date",
			"posting_date",
			"gross_pay",
			"net_pay",
			"total_deduction",
			"currency",
			"docstatus",
		],
		order_by="start_date desc",
		limit=limit,
		ignore_permissions=False
	)

	result = []
	for slip in salary_slips:
		result.append(
			{
				"id": slip.name,
				"employee": slip.employee,
				"employee_name": slip.employee_name,
				"start_date": str(slip.start_date),
				"end_date": str(slip.end_date),
				"posting_date": str(slip.posting_date),
				"gross_pay": float(slip.gross_pay or 0),
				"net_pay": float(slip.net_pay or 0),
				"total_deduction": float(slip.total_deduction or 0),
				"currency": slip.currency,
				"status": "Submitted" if slip.docstatus == 1 else "Draft",
			}
		)

	return result


@frappe.whitelist()
def get_salary_slip_details(slip_name: str):
	"""
	Get detailed salary slip information.
	Uses has_permission to verify access to the specific document.
	"""
	if not frappe.has_permission("Salary Slip", "read", slip_name):
		frappe.throw(_("You are not authorized to view this salary slip"))

	from frappe.utils import getdate
	slip = frappe.get_doc("Salary Slip", slip_name)

	return {
		"id": slip.name,
		"name": slip.name,
		"employee": slip.employee,
		"employee_name": slip.employee_name,
		"start_date": str(slip.start_date),
		"end_date": str(slip.end_date),
		"posting_date": str(slip.posting_date),
		"company": slip.company,
		"docstatus": slip.docstatus,
		"status": "Submitted" if slip.docstatus == 1 else ("Cancelled" if slip.docstatus == 2 else "Draft"),
		"month": getdate(slip.start_date).strftime("%B"),
		"year": getdate(slip.start_date).year,
		"working_days": float(slip.get("total_working_days") or slip.get("working_days") or 0),
		"payment_days": float(slip.get("payment_days") or 0),
		"lop_days": float(slip.get("lop_days") or slip.get("leave_without_pay") or 0),
		"absent_days": float(slip.get("absent_days") or 0),
		"leave_days": float(slip.get("leave_days") or 0),
		"holiday_days": float(slip.get("holiday_days") or 0),
		"gross_pay": float(slip.get("gross_pay") or 0),
		"net_pay": float(slip.get("net_pay") or 0),
		"total_deduction": float(slip.get("total_deduction") or 0),
		"currency": slip.get("currency"),
		"salary_slip_based_on_timesheet": slip.get("salary_slip_based_on_timesheet"),
		"hour_rate": float(slip.get("hour_rate") or 0),
		"total_working_hours": float(slip.get("total_working_hours") or 0),
		"earnings": [
			{"salary_component": e.salary_component, "component": e.salary_component, "amount": float(e.amount or 0), "abbr": e.abbr}
			for e in slip.earnings
		],
		"deductions": [
			{"salary_component": d.salary_component, "component": d.salary_component, "amount": float(d.amount or 0), "abbr": d.abbr}
			for d in slip.deductions
		],
		"timesheets": [
			{
				"time_sheet": t.get("time_sheet"),
				"name": t.get("time_sheet"),
				"working_hours": float(t.get("working_hours") or 0)
			}
			for t in getattr(slip, "timesheets", [])
		],
		"leave_details": get_leave_details(slip),
	}


