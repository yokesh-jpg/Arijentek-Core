@frappe.whitelist()
def save_salary_slip(doc):
	"""
	Saves or updates a Salary Slip document.
	"""
	from frappe.utils import flt

	if isinstance(doc, str):
		import json
		doc = json.loads(doc)

	is_new = not doc.get("name") or not frappe.db.exists("Salary Slip", doc.get("name"))

	if is_new:
		if not can_create_salary_slip():
			frappe.throw(_("You do not have permission to create Salary Slips"), frappe.PermissionError)
		ss = frappe.new_doc("Salary Slip")
	else:
		if not can_edit_salary_slip():
			frappe.throw(_("You do not have permission to edit Salary Slips"), frappe.PermissionError)
		ss = frappe.get_doc("Salary Slip", doc.get("name"))

	# Set main fields
	fields = [
		"employee",
		"posting_date",
		"company",
		"payroll_frequency",
		"start_date",
		"end_date",
		"salary_slip_based_on_timesheet",
		"working_days",
		"payment_days",
		"lop_days",
		"absent_days",
		"leave_days",
		"holiday_days",
		"gross_pay",
		"total_deduction",
		"net_pay",
		"hour_rate",
		"total_working_hours"
	]

	for field in fields:
		if field in doc and doc.get(field) is not None:
			ss.set(field, doc.get(field))

	# If salary structure is assigned to this employee, set it
	if not ss.salary_structure:
		ss.salary_structure = frappe.db.get_value(
			"Salary Structure Assignment",
			{"employee": ss.employee, "docstatus": 1},
			"salary_structure"
		)

	# Handle earnings table
	ss.set("earnings", [])
	for row in doc.get("earnings", []):
		comp_name = row.get("salary_component") or row.get("name")
		if comp_name:
			abbr = row.get("abbr") or row.get("salary_component_abbr") or frappe.db.get_value("Salary Component", comp_name, "salary_component_abbr")
			ss.append("earnings", {
				"salary_component": comp_name,
				"abbr": abbr,
				"amount": flt(row.get("amount"), 2),
			})

	# Handle deductions table
	ss.set("deductions", [])
	for row in doc.get("deductions", []):
		comp_name = row.get("salary_component") or row.get("name")
		if comp_name:
			abbr = row.get("abbr") or row.get("salary_component_abbr") or frappe.db.get_value("Salary Component", comp_name, "salary_component_abbr")
			ss.append("deductions", {
				"salary_component": comp_name,
				"abbr": abbr,
				"amount": flt(row.get("amount"), 2),
			})

	# Set gross, deduction, net
	ss.gross_pay = flt(doc.get("gross_pay"), 2)
	ss.total_deduction = flt(doc.get("total_deduction"), 2)
	ss.net_pay = flt(doc.get("net_pay") or (ss.gross_pay - ss.total_deduction), 2)

	# If salary_slip_based_on_timesheet is enabled and timesheets are present in doc:
	if ss.salary_slip_based_on_timesheet:
		ss.set("timesheets", [])
		for ts in doc.get("timesheets", []):
			ss.append("timesheets", {
				"time_sheet": ts.get("time_sheet") or ts.get("timesheet") or ts.get("name"),
				"working_hours": flt(ts.get("working_hours") or ts.get("total_hours"))
			})
		if not ss.timesheets and ss.start_date and ss.end_date:
			try:
				ss.get_emp_and_working_hours()
			except Exception:
				pass

	# Save/Insert
	ss.save(ignore_permissions=False)

	# Also handle submission if requested
	if doc.get("submit"):
		ss.submit()

		try:
			from arijentek_core.api.web_push import send_push_notification

			user_id = frappe.db.get_value("Employee", ss.employee, "user_id")
			if user_id:
				title = "Salary Slip Available"
				body = f"Your Salary Slip ({ss.name}) is now available."
				send_push_notification(user=user_id, title=title, body=body, url="/employee-portal#/payroll?tab=salary_slip")
		except Exception:
			frappe.log_error(frappe.get_traceback(), "Salary Slip Submission Notification Error")

	return ss.name


