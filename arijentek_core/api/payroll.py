@frappe.whitelist()
def get_payroll_summary(year: int | None = None, month: int | None = None, employee_id: str | None = None):
	"""
	Get payroll summary.
	"""
	from frappe.utils import flt, get_first_day, get_last_day, getdate

	filters = {"docstatus": 1}

	user = frappe.session.user
	roles = frappe.get_roles(user)
	has_global = "System Manager" in roles or "HR Manager" in roles or frappe.has_permission("Salary Slip", "submit")

	if not has_global:
		employee_id = _get_current_employee_id()
		if not employee_id:
			return {"total_earnings": 0.0, "total_deductions": 0.0, "total_net_pay": 0.0}
		filters["employee"] = employee_id
	elif employee_id and employee_id != "all":
		filters["employee"] = employee_id

	if year:
		if month:
			start_date = get_first_day(f"{year}-{int(month):02d}-01")
			end_date = get_last_day(start_date)
			filters["start_date"] = ["between", [start_date, end_date]]
		else:
			filters["start_date"] = [">=", f"{year}-01-01"]
			filters["end_date"] = ["<=", f"{year}-12-31"]
	else:
		year = getdate().year
		filters["start_date"] = [">=", f"{year}-01-01"]

	# Sam's User Permissions will automatically filter the list returned by get_list
	slips = frappe.get_list(
		"Salary Slip",
		filters=filters,
		fields=["gross_pay", "total_deduction", "net_pay"],
		ignore_permissions=False
	)

	summary = {
		"total_earnings": sum(flt(s.gross_pay) for s in slips),
		"total_deductions": sum(flt(s.total_deduction) for s in slips),
		"total_net_pay": sum(flt(s.net_pay) for s in slips)
	}

	return summary


def _get_allowed_employee_ids():
	"""
	Core method: Get list of employee IDs the current user is permitted to see.
	This follows strict User Permissions and ignores custom 'approver' logic.
	"""
	return frappe.get_list("Employee", pluck="name", ignore_permissions=False)


def _get_current_employee_id():
	"""Get the employee ID for the current logged-in user (internal helper)."""
	return frappe.db.get_value("Employee", {"user_id": frappe.session.user}, "name")


def get_leave_details(slip):
	"""Extract leave details from salary slip if available."""
	leave_details = []
	if hasattr(slip, "leave_details") and slip.leave_details:
		for leave in slip.leave_details:
			leave_details.append(
				{
					"leave_type": leave.leave_type,
					"leaves_allocated": float(leave.leaves_allocated or 0),
					"leaves_taken": float(leave.leaves_taken or 0),
					"leaves_remaining": float(leave.leaves_remaining or 0),
				}
			)
	return leave_details


