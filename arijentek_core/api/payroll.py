def get_payroll_entries(
	id: str | None = None,
	company: str | None = None,
	posting_date_start: str | None = None,
	posting_date_end: str | None = None,
	salary_slip_based_on_timesheet: int | str | None = None,
	page: int = 1,
	page_size: int = 0
):
	"""
	Returns a single Payroll Entry (as dict) if 'id' matches exactly.
	Otherwise, returns a filtered list of payroll entries for the UI.
	Supports server-side pagination when page_size > 0.
	"""
	if not can_read_payroll_entry():
		if page_size > 0:
			return {"data": [], "total": 0, "page": page, "page_size": page_size}
		return None if id else []

	page = max(1, cint(page) or 1)
	page_size = cint(page_size) or 0

	# List view queries with filters
	filters = {}

	if id:
		filters["name"] = ["like", f"%{id}%"]

	if company:
		filters["company"] = company

	if posting_date_start and posting_date_end:
		filters["posting_date"] = ["between", [posting_date_start, posting_date_end]]
	elif posting_date_start:
		filters["posting_date"] = [">=", posting_date_start]
	elif posting_date_end:
		filters["posting_date"] = ["<=", posting_date_end]

	if salary_slip_based_on_timesheet is not None:
		if isinstance(salary_slip_based_on_timesheet, str):
			if salary_slip_based_on_timesheet.lower() in ("true", "1", "yes"):
				filters["salary_slip_based_on_timesheet"] = 1
			elif salary_slip_based_on_timesheet.lower() in ("false", "0", "no"):
				filters["salary_slip_based_on_timesheet"] = 0
		else:
			filters["salary_slip_based_on_timesheet"] = 1 if salary_slip_based_on_timesheet else 0

	if page_size > 0:
		total = frappe.db.count("Payroll Entry", filters=filters)
		offset = (page - 1) * page_size
		entries = frappe.get_all(
			"Payroll Entry",
			filters=filters,
			fields=["*"],
			order_by="creation desc",
			limit_start=offset,
			limit_page_length=page_size
		)
		return {
			"data": entries,
			"total": total,
			"page": page,
			"page_size": page_size
		}

	entries = frappe.get_all(
		"Payroll Entry",
		filters=filters,
		fields=["*"],
		order_by="creation desc"
	)

	return entries


