@frappe.whitelist()
def get_payroll_eligible_employees(
	company: str,
	payroll_frequency: str | None = None,
	salary_slip_based_on_timesheet: int | str | None = None,
	branch: str | None = None,
	designation: str | None = None,
	department: str | None = None,
	grade: str | None = None,
	salary_structure: str | None = None,
	start_date: str | None = None,
	end_date: str | None = None
):
	"""
	Returns a list of eligible active employees based on filters.
	"""
	if not can_read_payroll_entry():
		return []

	emp_filters = {
		"status": "Active",
		"company": company
	}
	if branch:
		emp_filters["branch"] = branch
	if designation:
		emp_filters["designation"] = designation
	if department:
		emp_filters["department"] = department
	if grade:
		emp_filters["grade"] = grade

	employees = frappe.get_all(
		"Employee",
		filters=emp_filters,
		fields=["name", "employee_name", "branch", "designation", "department", "grade"]
	)

	conditions = ["ssa.docstatus = 1", "ssa.company = %(company)s"]
	query_params = {"company": company}

	if payroll_frequency:
		conditions.append("ss.payroll_frequency = %(payroll_frequency)s")
		query_params["payroll_frequency"] = payroll_frequency

	if salary_structure:
		conditions.append("ssa.salary_structure = %(salary_structure)s")
		query_params["salary_structure"] = salary_structure

	is_hourly = 0
	if salary_slip_based_on_timesheet is not None:
		if isinstance(salary_slip_based_on_timesheet, str):
			if salary_slip_based_on_timesheet.lower() in ("true", "1", "yes"):
				is_hourly = 1
			elif salary_slip_based_on_timesheet.lower() in ("false", "0", "no"):
				is_hourly = 0
		elif salary_slip_based_on_timesheet:
			is_hourly = 1
		conditions.append("ss.salary_slip_based_on_timesheet = %(is_hourly)s")
		query_params["is_hourly"] = is_hourly

	sql_query = f"""
		SELECT DISTINCT ssa.employee
		FROM `tabSalary Structure Assignment` ssa
		JOIN `tabSalary Structure` ss ON ssa.salary_structure = ss.name
		WHERE {" AND ".join(conditions)}
	"""
	assigned_employees_res = frappe.db.sql(sql_query, query_params, as_dict=True)
	assigned_employees = [r.employee for r in assigned_employees_res]

	if not assigned_employees:
		return []

	eligible_employees = [emp for emp in employees if emp.name in assigned_employees]
	return eligible_employees


@frappe.whitelist()
def save_payroll_entry(doc):
	"""
	Saves a Payroll Entry and generates Salary Slips for selected employees.
	"""
	if isinstance(doc, str):
		import json
		doc = json.loads(doc)

	is_new = not doc.get("name") or not frappe.db.exists("Payroll Entry", doc.get("name"))

	if is_new:
		if not can_create_payroll_entry():
			frappe.throw(_("You do not have permission to create Payroll Entries"), frappe.PermissionError)
		pe = frappe.new_doc("Payroll Entry")
	else:
		if not can_edit_payroll_entry():
			frappe.throw(_("You do not have permission to edit Payroll Entries"), frappe.PermissionError)
		pe = frappe.get_doc("Payroll Entry", doc.get("name"))

	fields = [
		"posting_date",
		"company",
		"currency",
		"payroll_frequency",
		"start_date",
		"end_date",
		"salary_slip_based_on_timesheet",
		"payroll_payable_account",
	]

	for field in fields:
		if field in doc and doc.get(field) is not None:
			pe.set(field, doc.get(field))

	pe.exchange_rate = pe.exchange_rate or 1.0

	if not pe.payroll_payable_account and pe.company:
		pe.payroll_payable_account = frappe.db.get_value("Company", pe.company, "default_payroll_payable_account")

	if pe.payroll_payable_account and frappe.db.exists("Account", pe.payroll_payable_account):
		if frappe.db.get_value("Account", pe.payroll_payable_account, "account_type") != "Payable":
			frappe.db.set_value("Account", pe.payroll_payable_account, "account_type", "Payable")

	pe.set("employees", [])
	selected_employees = doc.get("employees") or []
	for emp in selected_employees:
		emp_id = emp.get("employee") if isinstance(emp, dict) else emp
		pe.append("employees", {
			"employee": emp_id
		})

	pe.number_of_employees = len(pe.employees)

	try:
		# Start database transaction
		frappe.db.begin()

		pe.save(ignore_permissions=False)

		if doc.get("submit"):
			# Standard Frappe HRMS automatically creates Draft Salary Slips during pe.submit() via the on_submit hook!
			pe.submit()
		else:
			# If we are not submitting the Payroll Entry, manually create the Draft Salary Slips.
			pe.create_salary_slips()

		# Commit transaction
		frappe.db.commit()

	except Exception as e:
		# Rollback transaction on failure
		frappe.db.rollback()
		raise e

	return pe.name


@frappe.whitelist()
def get_employee_salary_slip_details(employee: str, start_date: str, end_date: str):
	"""
	Retrieves employee payroll, attendance, holiday and timesheet data for salary slip creation.
	"""
	if not can_read_salary_slip():
		frappe.throw(_("You do not have permission to read Salary Slips"), frappe.PermissionError)

	from frappe.utils import flt, getdate

