@frappe.whitelist()
def report_payroll_entry_list(from_date=None, to_date=None, employee=None, export=0, pdf=0):
	"""
	Returns Payroll Entry list for report, filtering by Posting Date and Employee.
	Lists all employees in each payroll entry as a comma-separated ID - Name string.
	"""
	if not can_view_all_payroll():
		frappe.throw(_("You are not authorized to view payroll reports"), frappe.PermissionError)
	from frappe.utils import getdate, now_datetime
	from frappe.utils.pdf import get_pdf
	from frappe.utils.xlsxutils import build_xlsx_response

	conditions = ["pe.docstatus < 2"]
	params = {}

	if from_date and to_date:
		conditions.append("pe.posting_date BETWEEN %(from_date)s AND %(to_date)s")
		params["from_date"] = getdate(from_date)
		params["to_date"] = getdate(to_date)
	elif from_date:
		conditions.append("pe.posting_date >= %(from_date)s")
		params["from_date"] = getdate(from_date)
	elif to_date:
		conditions.append("pe.posting_date <= %(to_date)s")
		params["to_date"] = getdate(to_date)

	if employee:
		conditions.append("""
			pe.name IN (
				SELECT parent FROM `tabPayroll Employee Detail` WHERE employee = %(employee)s
			)
		""")
		params["employee"] = employee

	where_clause = " AND ".join(conditions)

	query = f"""
		SELECT
			pe.name,
			DATE_FORMAT(pe.posting_date, '%%Y-%%m-%%d') as posting_date,
			DATE_FORMAT(pe.start_date, '%%Y-%%m-%%d') as start_date,
			DATE_FORMAT(pe.end_date, '%%Y-%%m-%%d') as end_date,
			CASE
				WHEN pe.docstatus = 1 THEN 'Submitted'
				WHEN pe.docstatus = 0 THEN 'Draft'
				WHEN pe.docstatus = 2 THEN 'Cancelled'
				ELSE pe.status
			END as status
		FROM `tabPayroll Entry` pe
		WHERE {where_clause}
		ORDER BY pe.posting_date DESC, pe.name DESC
	"""

	entries = frappe.db.sql(query, params, as_dict=True)

	# Aggregate employee details for each Payroll Entry
	result = []
	for entry in entries:
		emp_query = """
			SELECT employee, employee_name
			FROM `tabPayroll Employee Detail`
			WHERE parent = %s
			ORDER BY idx ASC, employee ASC
		"""
		emp_records = frappe.db.sql(emp_query, (entry.name,), as_dict=True)

		emp_list = []
		for emp in emp_records:
			emp_id = emp.get("employee") or ""
			emp_name = emp.get("employee_name") or ""
			if emp_id and emp_name:
				emp_list.append(f"{emp_id} - {emp_name}")
			elif emp_id:
				emp_list.append(emp_id)

		employees_str = ", ".join(emp_list) if emp_list else "-"
		payroll_period = f"{entry.start_date} to {entry.end_date}" if entry.start_date and entry.end_date else "-"

		result.append({
			"name": entry.name,
			"posting_date": entry.posting_date or "",
			"payroll_period": payroll_period,
			"employees": employees_str,
			"status": entry.status or "Draft"
		})

	if int(export):
		xlsx_data = [["Payroll ID", "Posting Date", "Payroll Period", "Employees", "Status"]]
		for r in result:
			xlsx_data.append([
				r["name"],
				r["posting_date"],
				r["payroll_period"],
				r["employees"],
				r["status"]
			])

		build_xlsx_response(xlsx_data, "Payroll_Entry_Report")
		return

	if int(pdf):
		context = {
			"data": result,
			"filters": {
				"from_date": from_date,
				"to_date": to_date,
				"employee": employee
			}
		}

		html = frappe.render_template("arijentek_core/templates/reports/payroll_entry_report.html", context)
		pdf_binary = get_pdf(html, {
			"page-size": "A4",
			"orientation": "Landscape",
			"margin-top": "10mm",
			"margin-bottom": "10mm",
			"margin-left": "8mm",
			"margin-right": "8mm"
		})

		frappe.local.response.filename = f"Payroll_Entry_Report_{now_datetime().strftime('%Y%m%d')}.pdf"
		frappe.local.response.filecontent = pdf_binary
		frappe.local.response.type = "pdf"
		return

	return result


