@frappe.whitelist()
def generate_my_payslip(month: int | None = None, year: int | None = None):
	"""
	Generate a payslip for the current employee.
	All employees can generate their own payslips as a self-service feature.
	"""
	employee = _get_current_employee_id()
	if not employee:
		return {"success": False, "error": _("Employee record not found for the current user.")}

	import calendar

	from frappe.utils import cint, get_first_day, get_last_day, getdate

	# Default to previous month if not provided
	today = getdate()
	year = cint(year) if year else today.year
	month = cint(month) if month else (today.month - 1 if today.month > 1 else 12)

	if month < 1:
		month = 12
		year -= 1

	# Validation: Cannot generate for current or future months
	requested_date = getdate(f"{year}-{month:02d}-01")
	current_month_start = getdate(f"{today.year}-{today.month:02d}-01")

	if requested_date >= current_month_start:
		return {"success": False, "error": _("Payslips can only be generated for completed previous months.")}

	# Get pay period dates
	start_date = get_first_day(requested_date)
	end_date = get_last_day(requested_date)

	# Validation 1: Check if Salary Slip already exists for this employee
	existing_slip = frappe.db.exists(
		"Salary Slip",
		{
			"employee": employee,
			"start_date": start_date,
			"end_date": end_date,
			"docstatus": ["!=", 2],
		},
	)
	if existing_slip:
		return {
			"success": False,
			"error": _("The salary slip for {0} {1} is already generated.").format(
				calendar.month_name[month], year
			),
		}

	# Validation 2: Check if payroll is generated for that month (for the company)
	company = frappe.db.get_value("Employee", employee, "company")
	if not company:
		company = frappe.defaults.get_user_default("company")

	payroll_processed = frappe.db.count(
		"Salary Slip",
		{"company": company, "start_date": start_date, "end_date": end_date, "docstatus": 1},
	)

	if not payroll_processed:
		payroll_processed = frappe.db.count(
			"Payroll Entry",
			{"company": company, "start_date": start_date, "end_date": end_date, "docstatus": 1},
		)

	if not payroll_processed:
		return {
			"success": False,
			"error": _(
				"Payroll for {0} {1} has not been generated by HR yet. Please wait for HR to process payroll before generating your own slip."
			).format(calendar.month_name[month], year),
		}

	# Generate using PayslipGenerator
	try:
		from arijentek_core.payroll.payslip_generator import PayslipGenerator

		generator = PayslipGenerator(company, start_date, end_date)
		slip = generator.generate_payslip(employee, submit=True)

		if slip:
			return {
				"success": True,
				"salary_slip": slip.name,
				"gross_pay": slip.gross_pay,
				"net_pay": slip.net_pay,
				"message": _("Salary Slip for {0} {1} created successfully").format(
					calendar.month_name[month], year
				),
			}
		else:
			error_msg = (
				generator.failed_employees[0]["error"] if generator.failed_employees else _("Unknown error")
			)
			return {"success": False, "error": error_msg}

	except ImportError:
		return {"success": False, "error": _("Payroll generation logic (arijentek_core) is missing.")}
	except Exception as e:
		frappe.log_error(frappe.get_traceback(), f"Self-Service Payslip Generation Error - {employee}")
		return {"success": False, "error": str(e)}


