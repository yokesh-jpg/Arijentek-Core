@frappe.whitelist()
def get_salary_components(id: str | None = None, name: str | None = None, status: str | None = None, page: int = 1, page_size: int = 0):
	"""
	Get list of Salary Components based on filters.
	Used for viewing and editing in data tables.
	Supports server-side pagination when page_size > 0.
	"""
	if not can_read_salary_componants():
		frappe.throw(_("You do not have permission to read Salary Components"), frappe.PermissionError)

	filters = {}
	if id:
		filters["name"] = ["like", f"%{id}%"]

	if name:
		filters["salary_component"] = ["like", f"%{name}%"]

	if status and status not in ["All", ""]:
		filters["type"] = status

	page = max(1, cint(page) or 1)
	page_size = cint(page_size) or 0

	if page_size > 0:
		total = frappe.db.count("Salary Component", filters=filters)
		offset = (page - 1) * page_size
		components = frappe.get_list(
			"Salary Component",
			filters=filters,
			fields=[
				"name",
				"salary_component",
				"salary_component_abbr",
				"type",
				"description",
				"condition",
				"formula",
				"amount_based_on_formula",
				"amount"
			],
			order_by="name asc",
			limit_start=offset,
			limit_page_length=page_size
		)
		return {
			"data": components,
			"total": total,
			"page": page,
			"page_size": page_size
		}

	components = frappe.get_list(
		"Salary Component",
		filters=filters,
		fields=[
			"name",
			"salary_component",
			"salary_component_abbr",
			"type",
			"description",
			"condition",
			"formula",
			"amount_based_on_formula",
			"amount"
		],
		order_by="name asc",
		limit=0
	)

	return components


