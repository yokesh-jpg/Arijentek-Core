@frappe.whitelist()
def save_salary_structure(doc):
	"""
	Saves or updates a Salary Structure document along with earnings and deductions.
	"""
	if isinstance(doc, str):
		import json
		doc = json.loads(doc)

	is_new = not doc.get("name") or not frappe.db.exists("Salary Structure", doc.get("name"))

	if is_new:
		if not can_create_salary_structure():
			frappe.throw(_("You do not have permission to create Salary Structures"), frappe.PermissionError)
		salary_struct = frappe.new_doc("Salary Structure")
		struct_name = doc.get("name") or doc.get("salary_structure_name")
		if struct_name:
			salary_struct.name = struct_name
	else:
		if not can_edit_salary_structure():
			frappe.throw(_("You do not have permission to edit Salary Structures"), frappe.PermissionError)
		salary_struct = frappe.get_doc("Salary Structure", doc.get("name"))

	fields = [
		"company",
		"currency",
		"is_active",
		"payroll_frequency",
		"salary_slip_based_on_timesheet",
		"hour_rate",
		"salary_component",
	]

	for field in fields:
		if field in doc and doc.get(field) is not None:
			salary_struct.set(field, doc.get(field))

	# Ensure default company currency is set if currency is not provided
	if not salary_struct.currency and salary_struct.company:
		company_currency = frappe.db.get_value("Company", salary_struct.company, "default_currency")
		salary_struct.currency = company_currency or frappe.defaults.get_global_default("currency") or "USD"

	# Handle earnings table
	salary_struct.set("earnings", [])
	for row in doc.get("earnings", []):
		comp_name = row.get("salary_component") or row.get("name")
		if comp_name:
			comp_doc = frappe.db.get_value(
				"Salary Component",
				comp_name,
				["amount_based_on_formula", "amount", "formula", "condition", "salary_component_abbr"],
				as_dict=True
			) or {}
			is_formula = 1 if (row.get("amount_based_on_formula") or comp_doc.get("amount_based_on_formula")) else 0
			amount_val = row.get("amount") if row.get("amount") is not None else comp_doc.get("amount", 0)
			formula_val = row.get("formula") or comp_doc.get("formula", "")
			condition_val = row.get("condition") or comp_doc.get("condition", "")
			abbr_val = row.get("salary_component_abbr") or row.get("abbr") or comp_doc.get("salary_component_abbr", "")

			salary_struct.append("earnings", {
				"salary_component": comp_name,
				"abbr": abbr_val,
				"amount_based_on_formula": is_formula,
				"amount": amount_val or 0,
				"formula": formula_val or "",
				"condition": condition_val or "",
			})

	# Handle deductions table
	salary_struct.set("deductions", [])
	for row in doc.get("deductions", []):
		comp_name = row.get("salary_component") or row.get("name")
		if comp_name:
			comp_doc = frappe.db.get_value(
				"Salary Component",
				comp_name,
				["amount_based_on_formula", "amount", "formula", "condition", "salary_component_abbr"],
				as_dict=True
			) or {}
			is_formula = 1 if (row.get("amount_based_on_formula") or comp_doc.get("amount_based_on_formula")) else 0
			amount_val = row.get("amount") if row.get("amount") is not None else comp_doc.get("amount", 0)
			formula_val = row.get("formula") or comp_doc.get("formula", "")
			condition_val = row.get("condition") or comp_doc.get("condition", "")
			abbr_val = row.get("salary_component_abbr") or row.get("abbr") or comp_doc.get("salary_component_abbr", "")

			salary_struct.append("deductions", {
				"salary_component": comp_name,
				"abbr": abbr_val,
				"amount_based_on_formula": is_formula,
				"amount": amount_val or 0,
				"formula": formula_val or "",
				"condition": condition_val or "",
			})

	if salary_struct.docstatus == 1:
		salary_struct.db_set("docstatus", 0)

	salary_struct.save(ignore_permissions=False)
	salary_struct.submit()
	return salary_struct.name


